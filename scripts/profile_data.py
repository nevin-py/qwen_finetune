#!/usr/bin/env python3
"""Profile all local datasets and databases -> reports/data_profile.md.

Covers: question counts/distributions, per-database schema shape, row counts,
and db_id coverage. Uses read-only SQLite connections only.
"""
from __future__ import annotations

import contextlib
import io
import json
import sqlite3
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "reports" / "data_profile.md"


def load(rel: str) -> list[dict]:
    return json.loads((DATA / rel).read_text())


def db_path(root: str, db_id: str) -> Path:
    return DATA / root / db_id / f"{db_id}.sqlite"


def profile_db(path: Path) -> dict:
    con = sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=5)
    try:
        rows = con.execute(
            "SELECT name, sql FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name").fetchall()
        tables, total_rows = [], 0
        for name, ddl in rows:
            n_rows = con.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
            cols = [c[1] for c in con.execute(f'PRAGMA table_info("{name}")')]
            fks = [c[2] for c in con.execute(f'PRAGMA foreign_key_list("{name}")')]
            pk = [c[1] for c in con.execute(f'PRAGMA table_info("{name}")') if c[5]]
            tables.append({"table": name, "cols": cols, "pk": pk, "fk": fks,
                           "rows": n_rows})
            total_rows += n_rows
        return {"db": path.stem, "tables": tables, "rows": total_rows}
    finally:
        con.close()


def main() -> None:
    spider_train, spider_dev = load("spider/train_spider.json"), load("spider/dev.json")
    sparc_train, sparc_dev = load("sparc/train.json"), load("sparc/dev.json")
    bird_dev = load("bird/dev.json")

    def qid(q: dict) -> str:  # SParC uses database_id, others db_id
        return q.get("db_id") or q["database_id"]

    def sparc_turns(items):  # interaction phases + final turns (duplicates reported)
        inter = sum(len(x["interaction"]) for x in items)
        finals = sum(1 for x in items if x.get("final"))
        dup = sum(1 for x in items if x.get("final")
                  and x["interaction"] and x["interaction"][-1]["query"] == x["final"]["query"])
        return inter, finals, dup

    st = sparc_turns(sparc_train)
    sv = sparc_turns(sparc_dev)
    bird_ids = sorted({qid(q) for q in bird_dev})
    spider_ids = sorted({qid(q) for q in spider_dev} | {qid(q) for q in spider_train})

    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        print("# Data Profile")
        print("\nGenerated by `scripts/profile_data.py` — do not edit by hand.\n")
        print("## Datasets\n")
        print("| split | items | notes |")
        print("|---|---|---|")
        print(f"| spider train_spider.json | {len(spider_train)} | training (+ val carve) |")
        print(f"| spider dev.json | {len(spider_dev)} | **locked test** |")
        print(f"| sparc train.json | {len(sparc_train)} | eval-only (multi-turn) |")
        print(f"| sparc dev.json | {len(sparc_dev)} | eval-only (multi-turn) |")
        print(f"| bird dev.json | {len(bird_dev)} | **locked held-out** |")
        print(f"\nSParC turns — train: {st[0]} interaction + {st[1]} final "
              f"({st[2]} duplicate the last interaction query); "
              f"dev: {sv[0]} + {sv[1]} ({sv[2]} duplicate).")
        print(f"\nBIRD difficulty distribution: "
              f"{dict(Counter(q['difficulty'] for q in bird_dev))}")
        print(f"BIRD questions with evidence (foreign keys): "
              f"{sum(1 for q in bird_dev if q.get('evidence'))}/{len(bird_dev)}")
        print(f"\nDatabase coverage: {len(spider_ids)} Spider db_ids (train+dev), "
              f"{len(bird_ids)} BIRD db_ids.")

        print("\n## Databases\n")
        print("| db | dataset | tables | columns | rows |")
        print("|---|---|---|---|---|")
        totals = {"tables": 0, "cols": 0, "rows": 0}
        for db_id in spider_ids:
            p = db_path("spider/database", db_id)
            if not p.exists():
                print(f"| {db_id} | spider | MISSING | | |")
                continue
            prof = profile_db(p)
            nc = sum(len(t["cols"]) for t in prof["tables"])
            totals = {k: totals[k] + v for k, v in
                      {"tables": len(prof["tables"]), "cols": nc, "rows": prof["rows"]}.items()}
            print(f"| {db_id} | spider | {len(prof['tables'])} | {nc} | {prof['rows']} |")
        for db_id in bird_ids:
            p = db_path("bird/databases", db_id)
            if not p.exists():
                print(f"| {db_id} | bird | MISSING | | |")
                continue
            prof = profile_db(p)
            nc = sum(len(t["cols"]) for t in prof["tables"])
            print(f"| {db_id} | bird | {len(prof['tables'])} | {nc} | {prof['rows']} |")
        print(f"\n**Totals (Spider): {totals['tables']} tables, "
              f"{totals['cols']} columns, {totals['rows']} rows.**")

    OUT.write_text(buf.getvalue())
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()