#!/usr/bin/env python3
"""Stage 0.2: cross-split near-duplicate / leakage audit (checklist 0.2).

Compares the three Spider splits against each other on:
  1. exact (db_id, normalized question) pairs
  2. exact normalized gold SQL (same-db and cross-db)
  3. near-duplicate questions (5-word shingles, Jaccard >= 0.9)

Data-level statistics only — no model output is read and no configuration
decision depends on dev results. Writes ``reports/leakage_audit.md``.
"""
from __future__ import annotations

import json
import re
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHINGLE = 5
JACCARD = 0.9


def norm_question(q: str) -> str:
    return " ".join(re.sub(r"[^a-z0-9 ]+", " ", q.lower()).split())


def norm_sql(q: str) -> str:
    return " ".join(q.lower().split())


def shingles(q: str) -> set[str]:
    toks = norm_question(q).split()
    if len(toks) < SHINGLE:
        return {" ".join(toks)} if toks else set()
    return {" ".join(toks[i:i + SHINGLE]) for i in range(len(toks) - SHINGLE + 1)}


def load(name: str, path: Path) -> list[dict]:
    rows = json.loads(path.read_text())
    print(f"loaded {name}: {len(rows)}")
    return rows


def main() -> None:
    t0 = time.time()
    spider = ROOT / "data" / "spider"
    splits = {
        "train": load("train", ROOT / "data" / "splits" / "train.json"),
        "val": load("val", ROOT / "data" / "splits" / "val.json"),
        "dev (locked test)": load("dev", spider / "dev.json"),
    }

    lines = ["# Cross-split leakage audit",
             "", f"5-word shingles, Jaccard >= {JACCARD}; generated by "
                 "`scripts/audit_leakage.py`.", ""]

    names = list(splits)
    for i, a in enumerate(names):
        for b in names[i + 1:]:
            qa = {(x["db_id"], norm_question(x["question"])) for x in splits[a]}
            qb = {(x["db_id"], norm_question(x["question"])) for x in splits[b]}
            same_db_q = qa & qb
            sa: dict[str, set[str]] = {}
            for x in splits[a]:
                sa.setdefault(x["db_id"], set()).add(norm_sql(x["query"]))
            sb = {}
            for x in splits[b]:
                sb.setdefault(x["db_id"], set()).add(norm_sql(x["query"]))
            same_db_sql = {d: v & sb[d] for d, v in sa.items() if d in sb}
            same_db_sql = {d: v for d, v in same_db_sql.items() if v}
            sql_a = {norm_sql(x["query"]) for x in splits[a]}
            sql_b = {norm_sql(x["query"]) for x in splits[b]}

            # near-duplicate questions: inverted shingle index over a -> candidates
            index: dict[str, set[int]] = {}
            a_rows = splits[a]
            a_sh = []
            for idx, x in enumerate(a_rows):
                sh = shingles(x["question"])
                a_sh.append(sh)
                for s in sh:
                    index.setdefault(s, set()).add(idx)
            near: list[tuple[int, int]] = []
            for j, y in enumerate(splits[b]):
                shy = shingles(y["question"])
                if not shy:
                    continue
                cand: set[int] = set()
                for s in shy:
                    cand |= index.get(s, set())
                for k in cand:
                    inter = len(a_sh[k] & shy)
                    union = len(a_sh[k] | shy)
                    if union and inter / union >= JACCARD:
                        near.append((k, j))

            lines.append(f"## {a} vs {b}")
            lines.append(f"- exact (db_id, question) overlap: {len(same_db_q)}")
            lines.append(f"- identical normalized SQL (same db): "
                         f"{sum(len(v) for v in same_db_sql.values())}")
            lines.append(f"- identical normalized SQL (any db): "
                         f"{len(sql_a & sql_b)}")
            lines.append(f"- near-duplicate questions (Jaccard >= {JACCARD}): "
                         f"{len(near)}")
            for k, j in near[:5]:
                lines.append(f"  - `{a_rows[k]['question']}` ⇄ "
                             f"`{splits[b][j]['question']}`")
            lines.append("")

    out = ROOT / "reports" / "leakage_audit.md"
    out.write_text("\n".join(lines) + f"\n_generated in {time.time()-t0:.0f}s_\n")
    print(f"wrote {out.relative_to(ROOT)} ({time.time()-t0:.0f}s)")


if __name__ == "__main__":
    main()
